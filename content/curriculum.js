export function imUnit(grade, n) {
  return (IM_UNITS[grade] || []).find((u) => u.n === n) ?? null;
}

export function imUnitsFor(grade, ns = []) {
  return ns.map((n) => imUnit(grade, n)).filter(Boolean);
}

export function imCourseGuide(grade) {
  const slug = IM_GRADE_SLUG[grade];
  return slug
    ? `https://im.kendallhunt.com/k5/teachers/${slug}/course-guide/scope-and-sequence.html`
    : 'https://illustrativemathematics.org/math-curriculum/';
}
